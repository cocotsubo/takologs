export type GraphAtom = { x: number; y: number; el: string };
export type MolGraph = {
  name: string;
  atoms: GraphAtom[];
  bonds: [number, number][];
};

function g(
  name: string,
  atoms: [number, number, string][],
  bonds: [number, number][],
): MolGraph {
  return {
    name,
    atoms: atoms.map(([x, y, el]) => ({ x, y, el })),
    bonds,
  };
}

