const dicts: Record<Locale, typeof fr> = { fr, en };

function lookup(dict: typeof fr, key: string): string | undefined {
  const parts = key.split(".");
  let cur: unknown = dict;
  for (const p of parts) {
    if (cur == null || typeof cur !== "object") return undefined;
    cur = (cur as Record<string, unknown>)[p];
  }
  return typeof cur === "string" ? cur : undefined;
}

function interpolate(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] == null ? `{${k}}` : String(vars[k]),
  );
}

export function detectRegionLocale(): Locale {
  if (typeof window === "undefined") return "fr";
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    const langs = [
      ...(navigator.languages ?? []),
      navigator.language,
    ].filter(Boolean);
    const isFrance =
      tz === "Europe/Paris" ||
      langs.some((l) => {
        const region = (l || "").replace("_", "-").split("-")[1];
        return region?.toUpperCase() === "FR";
      });
    return isFrance ? "fr" : "en";
  } catch {
    return "en";
  }
}

export function readLangPref(): LangPref {
  if (typeof window === "undefined") return "auto";
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "fr" || v === "en" || v === "auto") return v;
  } catch {
    /* ignore */
  }
  return "auto";
}

export function resolveLocale(pref: LangPref): Locale {
  return pref === "auto" ? detectRegionLocale() : pref;
}

export function bootLocale(): Locale {
  return resolveLocale(readLangPref());
}

export function defaultExperienceTitle(locale: Locale, d = new Date()) {
  const tag = locale === "fr" ? "fr-FR" : "en-GB";
  const raw = d.toLocaleDateString(tag, {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  });
  return raw.charAt(0).toUpperCase() + raw.slice(1);
}

type I18nCtx = {
  locale: Locale;
  pref: LangPref;
  setPref: (p: LangPref) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  dateTag: string;
};

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // SSR + first client paint always use French so markup matches.
  // Region / saved pref is applied after mount.
  const [pref, setPrefState] = useState<LangPref>("auto");
  const [locale, setLocale] = useState<Locale>("fr");

  useEffect(() => {
    const p = readLangPref();
    setPrefState(p);
    const next = resolveLocale(p);
    setLocale(next);
    document.documentElement.lang = next;
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setPref = useCallback((p: LangPref) => {
    setPrefState(p);
    setLocale(resolveLocale(p));
    try {
      localStorage.setItem(LANG_KEY, p);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const dict = dicts[locale];
      let raw = lookup(dict, key);
      if (vars && typeof vars.n === "number" && vars.n !== 1) {
        const plural = lookup(dict, `${key}_plural`);
        if (plural) raw = plural;
      }
      if (!raw) raw = lookup(dicts.fr, key) ?? key;
      return interpolate(raw, vars);
    },
    [locale],
  );

  const value = useMemo<I18nCtx>(
    () => ({
      locale,
      pref,
      setPref,
      t,
      dateTag: locale === "fr" ? "fr-FR" : "en-GB",
    }),
    [locale, pref, setPref, t],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
